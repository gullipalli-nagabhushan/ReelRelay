"""Ephemeral download progress tracking.

Tokens are generated by the browser and passed to both ``/api/prepare`` and
``/download``. State lives in memory only: it is never written to disk, contains
no media, and is pruned shortly after a download finishes. This is what powers
the live elapsed-time, byte-count and speed readout in the UI.
"""

from __future__ import annotations

import threading
import time
from typing import Any

_STALE_AFTER = 3600.0  # seconds a finished/abandoned entry is kept
_MAX_ENTRIES = 512


class ProgressRegistry:
    """Thread-safe, bounded registry of download progress snapshots."""

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._entries: dict[str, dict[str, Any]] = {}

    # ------------------------------------------------------------------ #
    # Lifecycle
    # ------------------------------------------------------------------ #

    def create(
        self,
        token: str,
        filename: str = "",
        total: int | None = None,
        *,
        estimated: bool = False,
    ) -> None:
        if not token:
            return
        now = time.time()
        with self._lock:
            self._prune_locked(now)
            existing = self._entries.get(token)
            if existing:
                # A retry reuses the token: keep the original start time so the
                # elapsed counter tells the truth across reconnects.
                existing.update(
                    {
                        "filename": filename or existing.get("filename", ""),
                        "total": int(total) if total else existing.get("total"),
                        "estimated": bool(estimated) if total else existing.get("estimated", False),
                        "state": "preparing",
                        "error": None,
                        "updated_at": now,
                    }
                )
                return
            self._entries[token] = {
                "token": token,
                "filename": filename,
                "total": int(total) if total else None,
                "estimated": bool(estimated),
                "state": "preparing",
                "sent": 0,
                "error": None,
                "started_at": now,
                "updated_at": now,
                "first_byte_at": None,
                "last_sent": 0,
                "last_at": 0.0,
                "speed": 0.0,
            }

    def begin(
        self,
        token: str,
        total: int | None = None,
        *,
        estimated: bool | None = None,
    ) -> None:
        """Mark the response as open and start counting elapsed time."""
        now = time.time()
        with self._lock:
            entry = self._entries.get(token)
            if entry is None:
                self._entries[token] = {
                    "token": token,
                    "filename": "",
                    "total": int(total) if total else None,
                    "estimated": bool(estimated),
                    "state": "streaming",
                    "sent": 0,
                    "error": None,
                    "started_at": now,
                    "updated_at": now,
                    "first_byte_at": now,
                    "last_sent": 0,
                    "last_at": now,
                    "speed": 0.0,
                }
                return
            first_begin = entry.get("state") != "streaming" and not entry.get("sent")
            entry["state"] = "streaming"
            entry["error"] = None
            if total:
                entry["total"] = int(total)
            if estimated is not None and (total or estimated):
                entry["estimated"] = bool(estimated)
            if first_begin:
                # Count from the moment bytes really start flowing, not from
                # the metadata request that prepared the download.
                entry["started_at"] = now
                entry["last_at"] = now
                entry["last_sent"] = 0
            entry["first_byte_at"] = entry.get("first_byte_at") or now
            entry["last_at"] = entry.get("last_at") or now
            entry["updated_at"] = now

    def update(
        self,
        token: str,
        sent: int,
        total: int | None = None,
        *,
        estimated: bool | None = None,
    ) -> None:
        now = time.time()
        with self._lock:
            entry = self._entries.get(token)
            if entry is None:
                return
            sent = max(0, int(sent))
            entry["sent"] = sent
            if total:
                entry["total"] = int(total)
            if estimated is not None and (total or estimated):
                entry["estimated"] = bool(estimated)
            entry["state"] = "streaming"
            entry["updated_at"] = now
            if entry.get("first_byte_at") is None:
                entry["first_byte_at"] = now

            last_at = float(entry.get("last_at") or 0.0)
            last_sent = int(entry.get("last_sent") or 0)
            if last_at and now - last_at >= 0.2:
                instant = max(0.0, (sent - last_sent) / (now - last_at))
                previous = float(entry.get("speed") or 0.0)
                # Smooth the number so the UI does not jitter every 700 ms.
                entry["speed"] = instant if previous <= 0 else previous * 0.6 + instant * 0.4
                entry["last_at"] = now
                entry["last_sent"] = sent

    def finish(self, token: str, error: str | None = None) -> None:
        now = time.time()
        with self._lock:
            entry = self._entries.get(token)
            if entry is None:
                return
            entry["state"] = "error" if error else "done"
            entry["error"] = error
            entry["updated_at"] = now
            if not error:
                total = entry.get("total")
                # Only relay streams have a real Content-Length. Estimated
                # ffmpeg output is left at the actual byte count.
                if total and not entry.get("estimated"):
                    entry["sent"] = int(total)
                entry["speed"] = 0.0

    # ------------------------------------------------------------------ #
    # Reading
    # ------------------------------------------------------------------ #

    def get(self, token: str) -> dict[str, Any] | None:
        if not token:
            return None
        with self._lock:
            entry = self._entries.get(token)
            if entry is None:
                return None
            return self._snapshot_locked(entry)

    def _snapshot_locked(self, entry: dict[str, Any]) -> dict[str, Any]:
        now = time.time()
        sent = int(entry.get("sent") or 0)
        total = entry.get("total")
        total = int(total) if total else None
        estimated = bool(entry.get("estimated"))
        started_at = float(entry.get("started_at") or now)
        elapsed = max(0.0, now - started_at)
        speed = float(entry.get("speed") or 0.0)
        state = str(entry.get("state") or "preparing")
        # A stalled pipe (ffmpeg flushing the container, a slow origin) should
        # stop advertising the last measured speed.
        last_update = float(entry.get("updated_at") or now)
        stalled = state == "streaming" and now - last_update > 2.5
        if stalled:
            speed = 0.0
        percent = None
        eta = None
        remaining = None
        if total and total > 0:
            if state == "done":
                percent = 100.0
                remaining = 0
            else:
                # Never claim 100% until the response has actually finished.
                cap = 99.9 if estimated else 100.0
                percent = round(min(cap, sent / total * 100.0), 1)
                remaining = max(0, total - sent)
                if speed > 0 and state == "streaming" and remaining:
                    eta = max(0.0, remaining / speed)
        if state == "done":
            eta = 0.0
        return {
            "ok": True,
            "token": entry.get("token"),
            "filename": entry.get("filename") or "",
            "state": state,
            "sent": sent,
            "total": total,
            "total_is_estimate": estimated,
            "percent": percent,
            "elapsed": round(elapsed, 1),
            "speed": int(speed),
            "stalled": stalled,
            "remaining": remaining,
            "eta": round(eta, 1) if eta is not None else None,
            "error": entry.get("error"),
        }

    # ------------------------------------------------------------------ #
    # Housekeeping
    # ------------------------------------------------------------------ #

    def _prune_locked(self, now: float) -> None:
        stale = [
            token
            for token, entry in self._entries.items()
            if now - float(entry.get("updated_at") or now) > _STALE_AFTER
        ]
        for token in stale:
            self._entries.pop(token, None)

        if len(self._entries) >= _MAX_ENTRIES:
            oldest = sorted(
                self._entries.items(),
                key=lambda item: float(item[1].get("updated_at") or 0.0),
            )
            for token, _ in oldest[: len(self._entries) - _MAX_ENTRIES + 1]:
                self._entries.pop(token, None)

    def clear(self) -> None:
        with self._lock:
            self._entries.clear()

    def __len__(self) -> int:
        with self._lock:
            return len(self._entries)


progress = ProgressRegistry()
